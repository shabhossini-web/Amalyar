/**
 * قرارِ شناسایی درآمد — **تنها تعریفِ «کِی پول مالِ ماست» در کلِ برنامه.**
 *
 * ⚠️ چرا لازم شد: تا دیروز درآمد جمعِ `Charge` بود، بی‌هیچ توجهی به اینکه عمل
 * انجام شده یا نه. یعنی لحظه‌ای که ادمین فرمِ ثبت‌نام را تأیید می‌کرد، کلِ مبلغ
 * در سودِ گزارش می‌نشست — برای عملی که هفتهٔ بعد بود. و چون `computeShares` روی
 * همان عدد کار می‌کند، سهمِ شرکا و جراح هم روی پولی تقسیم می‌شد که هنوز بابتش
 * کاری انجام نشده بود. اگر عمل لغو می‌شد، پولِ تقسیم‌شده باید از جیبِ شرکا
 * برمی‌گشت.
 *
 * قرار — همان چیزی که سامانهٔ قبلی درست انجام می‌داد:
 *
 *   پرداخت رسید      → **خزانه** (دارایی). مستقل از انجامِ عمل، همان لحظه.
 *   عمل انجام نشده   → **پیش‌دریافت**: بدهی به بیمار، نه درآمد.
 *   `opStatus=done`  → درآمد **شناسایی** می‌شود.
 *   لغو شد           → بدهی می‌ماند تا بازگردانده شود.
 *
 * ⚠️ بدهی برابرِ **پولِ رسیده** است، نه مبلغِ فاکتور: اگر بیمار ۳ میلیون بابتِ
 * خدمتِ ۵ میلیونی داده و عمل نشده، شرکت ۳ میلیون بدهکار است نه ۵. تعهدِ
 * انجام‌نشده (۲ میلیونِ باقی‌مانده) نه دارایی است نه بدهی — هنوز هیچ اتفاقی
 * نیفتاده.
 *
 * ⚠️ هیچ‌کدام از اینها **ذخیره نمی‌شود**. `opStatus` یک‌بار عوض می‌شود و همهٔ
 * گزارش‌ها باید همان لحظه درست شوند؛ ستونِ `recognizedRevenue` یعنی روزی که
 * کسی وضعیت را دستی برگرداند، عدد جا می‌ماند و دیگر معلوم نیست کدام درست است.
 */

/** وضعیتی که یعنی «کار انجام شده و پولش مالِ ماست». */
export const DONE = 'done';

export type MoneyRow = {
  /** جمعِ قلم‌های فاکتور — تعهدِ ثبت‌شده، صرف‌نظر از انجام. */
  contracted: number;
  /** جمعِ پرداخت‌ها — پولِ واقعاً رسیده. */
  collected: number;
  opStatus: string;
};

/** آیا درآمدِ این مراجعه شناسایی شده است؟ */
export const isEarned = (opStatus: string): boolean => opStatus === DONE;

/**
 * سه عددی که هر گزارشِ مالی باید بدهد.
 *
 * `recognized + deferred` عمداً برابرِ هیچ‌چیز نیست: اولی از فاکتور می‌آید و
 * دومی از پرداخت. جمع‌کردنشان یعنی قاطی‌کردنِ سود و نقدینگی.
 */
export function recognize(row: MoneyRow) {
  const earned = isEarned(row.opStatus);
  return {
    /// درآمدِ شناسایی‌شده — مبنای سود و مبنای تسویهٔ شرکا.
    recognized: earned ? row.contracted : 0,
    /// پیش‌دریافت — پولِ رسیده بابتِ کاری که هنوز نشده. بدهی به بیمار.
    deferred: earned ? 0 : row.collected,
    /// ماندهٔ بیمار: هرچه از فاکتور هنوز نرسیده. مستقل از شناسایی.
    due: Math.max(0, row.contracted - row.collected),
  };
}
