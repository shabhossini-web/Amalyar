/**
 * دلیل‌های لغو — **مجموعهٔ بسته، در کد** (تصمیمِ مالک ۱۴۰۵/۰۶/۲۶).
 *
 * ⚠️ چرا جدولِ تعریف‌شدنی نیست: متنِ هر دلیل **به دستِ بیمار می‌رسد**. فهرستی
 * که هر لحظه بشود عوضش کرد یعنی متنی که برای بیمار می‌رود غیرقابل‌پیش‌بینی
 * است. همان استدلالِ `JOB_ROLES`: دروازه‌ای که هر لحظه بشود عوضش کرد، دروازه
 * نیست. نقشِ تازه = یک ورودی این‌جا، نه یک ردیفِ آزاد در دیتابیس.
 *
 * ⚠️ و چرا دو متن: `label` چیزی است که کارکنان در کشویی می‌بینند، `patient`
 * چیزی است که برای بیمار می‌رود. اگر یکی بودند، کارکنان یا متنِ رسمیِ بلند را
 * در کشویی می‌دیدند یا بیمار کوتاه‌نویسیِ اداری را می‌گرفت.
 */
export type CancelKind = 'visit' | 'appointment';

export const CANCEL_REASONS: Record<string, { label: string; patient: string }> = {
  doctor: { label: 'تعویقِ پزشک', patient: 'به دلیلِ تغییرِ برنامهٔ پزشک' },
  patient: { label: 'درخواستِ بیمار', patient: 'به درخواستِ خودتان' },
  clinical: { label: 'شرایطِ بالینی', patient: 'به دلیلِ شرایطِ بالینی' },
  hospital: { label: 'مشکلِ بیمارستان', patient: 'به دلیلِ شرایطِ مرکزِ درمانی' },
  other: { label: 'سایر', patient: '' },
};

export const CANCEL_REASON_KEYS = Object.keys(CANCEL_REASONS);

/**
 * متنِ پیامکِ لغو.
 *
 * ⚠️ متنِ **نوبت** و **مراجعه** یکی نیست و نباید یکی شود: لغوِ نوبت یعنی «هنوز
 * چیزی ثبت نشده بود»، لغوِ مراجعه یعنی «کارِ ثبت‌شده لغو شد». یک متنِ مشترک
 * برای هر دو، به یکی از دو گروهِ بیمار دروغ می‌گوید.
 *
 * ⚠️ دلیلِ «سایر» متنِ بیمار ندارد (`patient: ''`) — عمداً. کارکنان دلیلِ واقعی
 * را در **یادداشتِ داخلی** می‌نویسند و بیمار پیامِ بدونِ دلیل می‌گیرد؛ بهتر از
 * آن است که «به دلیلِ سایر» برایش برود.
 */
export function cancelSms(kind: CancelKind, reasonKey: string, opts: { brand?: string | null; when?: string | null }) {
  const r = CANCEL_REASONS[reasonKey];
  const why = r?.patient ? ` ${r.patient}` : '';
  const when = opts.when ? ` ${opts.when}` : '';
  const head = opts.brand ? `${opts.brand}\n` : '';
  return kind === 'appointment'
    ? `${head}نوبتِ شما${when}${why} لغو شد. برای تعیینِ زمانِ تازه با ما تماس بگیرید.`
    : `${head}مراجعهٔ شما${when}${why} لغو شد. برای هماهنگیِ دوباره با ما تماس بگیرید.`;
}
