/**
 * کانونی‌سازیِ **محلِ تحویل** — خالص، بدونِ Prisma و Nest.
 *
 * چرا لازم است: کارشناس می‌نویسد «CSR»، راننده می‌نویسد «csr»، سومی «سی اس
 * آر» و چهارمی «C.S.R». هر چهار تا یک جای واقعی‌اند ولی چهار رشتهٔ متفاوت.
 * تا وقتی یکی نشوند، هیچ‌وقت نمی‌شود پرسید «کدام بیمارستان بیشتر تأخیر
 * دارد» — و این سؤالی است که **گذشته را نمی‌شود برایش بازسازی کرد**. پس
 * کانونی‌سازی باید هنگامِ **نوشتن** انجام شود، نه هنگامِ گزارش‌گیری.
 *
 * ⚠️ این نرمال‌ساز عمداً `normalizeName`ِ بیمارستان **نیست**: آن‌جا واژه‌های
 * «بیمارستان» و «دکتر» و «شهید» حذف می‌شوند چون در نامِ مرکز معنا اضافه
 * نمی‌کنند. این‌جا برعکس — «انبارِ بیمارستان» بدونِ واژهٔ «بیمارستان» به
 * «انبار» می‌رسد و با انبارِ مرکزی یکی می‌شود. حذفِ واژه این‌جا خطاست.
 *
 * ⚠️ متنِ آزاد **رد نمی‌شود**. اگر کارشناس چیزی نوشت که در فهرستِ استاندارد
 * نیست، همان‌طور که نوشته ذخیره می‌شود. قفل‌کردنِ فیلد یعنی کارشناسِ وسطِ
 * عمل نتواند واقعیت را ثبت کند، و آن بدتر از دادهٔ نامرتب است.
 */

const AR_TO_FA: Record<string, string> = {
  'ي': 'ی', 'ك': 'ک', 'ة': 'ه', 'ۀ': 'ه', 'أ': 'ا', 'إ': 'ا', 'آ': 'ا', 'ؤ': 'و', 'ئ': 'ی',
};
const DIGITS: Record<string, string> = {};
for (let i = 0; i < 10; i += 1) {
  DIGITS['۰۱۲۳۴۵۶۷۸۹'[i]] = String(i);
  DIGITS['٠١٢٣٤٥٦٧٨٩'[i]] = String(i);
}

/**
 * کلیدِ تطبیقِ یک محل.
 *
 * لاتینِ چندحرفی هم بدونِ فاصله می‌شود تا «سی اس آر» و «C S R» و «CSR» به یک
 * کلید برسند — ولی فقط وقتی همهٔ اجزا تک‌حرفی باشند، وگرنه «اتاق عمل» به
 * «اتاقعمل» می‌رسید و خوانا نبودنش مهم نیست، اشتباه‌بودنش مهم است: «اتاق
 * عمل ۲» و «اتاق عمل۲» باید یکی شوند ولی «اتاق عمل» و «اتاق ریکاوری» نه.
 */
export function placeKey(raw: string | null | undefined): string {
  if (!raw) return '';
  let s = String(raw);
  s = s.replace(/[يكةۀأإآؤئ]/g, (c) => AR_TO_FA[c] ?? c);
  s = s.replace(/[۰-۹٠-٩]/g, (c) => DIGITS[c] ?? c);
  // نیم‌فاصله، اعراب و کشیده → فاصله
  s = s.replace(/[‌‏‎ً-ْـ]/g, ' ');
  s = s.replace(/[()[\]{}«»"'’,،.\-_/\\|+*#]/g, ' ');
  s = s.toLowerCase();
  const words = s.split(/\s+/).filter(Boolean);
  // «سی اس آر» / «c s r» → همه تک‌حرفی: بچسبان. «اتاق عمل» دست‌نخورده می‌ماند.
  if (words.length > 1 && words.every((w) => w.length === 1)) return words.join('');
  return words.join(' ');
}

