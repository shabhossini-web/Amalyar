import { toEnDigits } from './identity';

/**
 * ⚠️ **جستجو باید ارقامِ فارسی و انگلیسی را یکی ببیند.**
 *
 * کاربرِ فارسی روی گوشی «۱۶» تایپ می‌کند، ولی کالایی که وارد شده «16» است —
 * یا برعکس. تا امروز جستجوی کاتالوگ و انبار متنِ خام را مستقیم به
 * `contains` می‌داد، پس همان کالایی که در فهرست پیشِ چشمِ کاربر بود با
 * تایپِ شماره‌اش «پیدا نشد» و کاربر نتیجه می‌گرفت که کاتالوگ خراب است.
 *
 * چرا نرمال‌سازیِ فقط **پرسش** کافی نیست: دادهٔ ثبت‌شده هم ممکن است ارقامِ
 * فارسی داشته باشد (شمارهٔ لاتی که با کیبوردِ فارسی وارد شده). پس هر دو
 * صورتِ عبارت جست‌وجو می‌شود، نه یکی.
 *
 * چرا این‌جا و نه داخلِ هر سرویس: سه سرویس جستجو دارند (بیمار، کالا، لات) و
 * تا امروز فقط یکی‌شان — آن هم فقط برای تلفن و کدِ ملی — این کار را می‌کرد.
 */
export function digitVariants(term: string): string[] {
  const raw = String(term ?? '').trim();
  if (!raw) return [];
  const en = toEnDigits(raw);
  const fa = en.replace(/[0-9]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]);
  // ترتیب مهم نیست ولی تکرار مهم است: عبارتِ بی‌رقم فقط یک شرط می‌سازد.
  return [...new Set([raw, en, fa])];
}

/**
 * شرط‌های `OR` برای یک عبارت روی چند ستون — با همهٔ صورت‌های رقمی.
 *
 * `fields` نامِ ستون‌هاست؛ `insensitive` برای ستون‌هایی که لاتین دارند
 * (نامِ برند، SKU) معنا دارد و برای فارسی بی‌اثر است ولی ضرری هم ندارد.
 */
export function textSearchOr(term: string, fields: string[]): any[] {
  const variants = digitVariants(term);
  const out: any[] = [];
  for (const v of variants) {
    for (const f of fields) {
      out.push({ [f]: { contains: v, mode: 'insensitive' } });
    }
  }
  return out;
}
