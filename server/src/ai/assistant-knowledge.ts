export interface GuideContext {
  kind: GuideKind;
  /** کلیدِ ماژول‌های **روشنِ** همین نصب (`features.enabled`). */
  enabled: ReadonlySet<string>;
  /** خدماتِ شرکت (`ionm`/`implant`)؛ مطب خالی. */
  services?: readonly string[];
}

/** بندی که برای این نصب می‌آید؟ نوع بخورد، (اگر ماژول دارد) همهٔ ماژول‌هایش روشن و (اگر خدمت دارد) یکی از خدمت‌هایش هست. */
export const guideApplies = (e: GuideEntry, ctx: GuideContext) =>
  (!e.kind || e.kind === ctx.kind)
  && (!e.modules?.length || e.modules.every((m) => ctx.enabled.has(m)))
  && (!e.services?.length || e.services.some((sv) => (ctx.services ?? []).includes(sv)));

/**
 * سطرِ ماژول به‌جای `label: hint`ِ رجیستری — فقط جایی که همان متنِ رجیستری برای این نوعِ نصب گمراه‌کننده
 * است. رجیستری یک متن برای همهٔ نصب‌ها دارد (ماتریسِ دسترسی)، ولی دستیار با مدیرِ **یک** نصب حرف می‌زند:
 * «پرتالِ جراح … در شرکت‌های نورو و ایمپلنت» برای مدیرِ مطب که کاشی‌اش «میزِ پزشک» است یعنی صفحه‌ای دیگر.
 */
const MODULE_LINE: Partial<Record<GuideKind, Record<string, string>>> = {
  clinic: { surgeon: 'میزِ پزشک (/app/surgeon): امروزِ من، بیمارانِ من، نتایجِ رسیده و بیلانِ پزشک — برای پزشکِ متصل به تعریفِ جراح.' },
};

/**
 * راهنمایی که دستیار برای **همین نصب** می‌بیند: یک خطِ «برچسب (مسیر): توضیح» برای هر ماژولِ روشن، و بندهای
 * هم‌نوع. نصبِ بی‌ماژول یا بی‌نوع (مثلاً سوییت) فقط بندهای همیشگی را می‌گیرد، نه همه را.
 */
export function assistantGuide(ctx: GuideContext): string {
  const modules = FEATURES
    .filter((f) => ctx.enabled.has(f.key))
    .map((f) => MODULE_LINE[ctx.kind]?.[f.key]
      ?? `${f.label}${FEATURE_ROUTES[f.key] ? ` (${FEATURE_ROUTES[f.key]})` : ''}${f.hint ? `: ${f.hint}` : ''}`);
  const entries = GUIDE.filter((e) => guideApplies(e, ctx)).map((e) => e.text);
  return [...modules, ...entries].join('\n');
}
