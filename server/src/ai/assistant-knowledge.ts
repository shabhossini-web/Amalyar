export interface GuideEntry {
  /** فقط برای این نوعِ نصب؛ نبودنش یعنی هر دو. */
  kind?: GuideKind;
  /**
   * فقط وقتی **همهٔ** این ماژول‌ها روشن باشند؛ نبودنش یعنی همیشه. «همه»، نه «یکی از»: بندی که از
   * `/app/dispatch` و `/app/tech` حرف می‌زند، در شرکتِ فقط‌ایمپلنت (بی‌چینش و بی‌پنلِ کارشناسی) با «یکی از»
   * می‌آمد و به دو صفحه‌ای ارجاع می‌داد که آن نصب ندارد — همان گیجیِ دستیار که نگهبانِ
   * `assistant-guide-unit.mjs` پیش از انتشار گرفت.
   */
  modules?: string[];
  /**
   * فقط وقتی شرکت **یکی از** این خدمات را دارد (`ionm` نورومانیتورینگ، `implant` ایمپلنت). ماژول‌ها کافی نبودند:
   * «فاکتورِ نورو» به ماژولِ `dashboard` بسته است که شرکتِ فقط‌ایمپلنت هم دارد، پس دستیار به آن شرکت از فاکتوری
   * می‌گفت که هرگز نمی‌بیند.
   */
  services?: string[];
  text: string;
}

