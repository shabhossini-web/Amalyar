-- روشن‌کردنِ ماژولِ «حمل‌ونقل» در نصبی که واقعاً نیروی حمل دارد.
--
-- گزارشِ مالک (۱۴۰۵/۰۷/۰۹، رهام): نقشِ «راننده» داده شد و تحویل روی تختهٔ روز ثبت شد، ولی نه
-- راننده کاشیِ «حمل‌ونقل» را می‌دید و نه خودِ سوپرادمین. علت: `20260921073000_restore_access_module`
-- عمداً `transport` را روشن نکرد («ظاهرشدنِ پرتالی که کسی نخواسته») و روی نصب‌هایی که یک‌بار
-- حوزه‌شان عوض شده بود خاموش ماند — در حالی که همان شرکت راننده تعریف می‌کند و تختهٔ حمل را به
-- کار می‌برد. نیروی حملِ فعال همان «خواستن» است؛ فقط چنین نصبی روشن می‌شود.
--
-- ⚠️ مطب دست نمی‌خورد (پلانِ حوزه‌اش حمل ندارد). کاشی همچنان فقط به دارندهٔ رکوردِ نیرو و
-- سوپرادمین نشان داده می‌شود (`eligibleFrom`)، و سوپرادمین از «سطوحِ دسترسی» خاموشش می‌کند.
UPDATE "features"
SET "enabled" = true, "updated_at" = now()
WHERE "key" = 'transport' AND "enabled" = false
  AND EXISTS (SELECT 1 FROM "transport_staff" WHERE "active" = true)
  AND NOT EXISTS (SELECT 1 FROM "settings" WHERE "key" = 'vertical' AND "value" = 'clinic');
