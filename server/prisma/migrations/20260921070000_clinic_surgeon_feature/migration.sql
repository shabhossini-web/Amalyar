-- بستهٔ ۵ — روشن‌کردنِ کاشیِ «میزِ پزشک» روی نصب‌هایی که **از قبل** روی مطب‌اند.
--
-- ⚠️ تلهٔ واقعی: پلانِ ماژول‌های هر حوزه (`server/src/config/verticals.ts`) فقط
-- در یک جا اعمال می‌شود — `ConfigService.setVertical`، یعنی لحظه‌ای که سوپرادمین
-- حوزه را **عوض** می‌کند. هیچ مسیرِ دیگری پلان را دوباره نمی‌نشاند:
-- `FeaturesService.ensureSeeded()` با `createMany({ skipDuplicates: true })` فقط
-- کلیدِ **غایب** را می‌سازد و به `enabled` دست نمی‌زند.
--
-- پس نصبی که پیش از این تغییر روی مطب رفته بود، همان موقع `features.surgeon`
-- را `enabled = false` گرفت (کلید در پلانِ قدیمیِ مطب نبود و حلقهٔ `setVertical`
-- هر کلیدِ خارج از پلان را خاموش می‌کند). افزودنِ `surgeon: 2` به پلانِ مطب در
-- کد، آن ردیفِ خاموش را روشن نمی‌کند — یعنی دقیقاً روی مشتری‌ای که این فیچر
-- برایش ساخته شده، میزِ پزشک برای هر کاربرِ غیرِ سوپرادمین نامرئی و ۴۰۳ می‌ماند:
-- `forUser` مقدارِ `allowed` را با `r.enabled` **AND** می‌کند و `FeatureGuard`
-- روی `enabled = false` می‌اندازد. و چون سوپرادمین از هر دو بی‌قید رد می‌شود،
-- هرکس با حسابِ مدیر تست کند همه‌چیز را سالم می‌بیند.
--
-- شرطِ `enabled = false` عمدی است: فقط ردیفی را برمی‌گرداند که **خودِ سامانه**
-- خاموش کرده بود. روی مطب هیچ مدیری دلیلی برای خاموش‌کردنِ دستی نداشته، چون
-- تا دیروز کاشی در مطب اصلاً نشان داده نمی‌شد.
-- `min_level = 2` همان مقدارِ پلانِ مطب است (`VERTICALS.clinic.features.surgeon`).
--
-- نصب‌های غیرِ مطب و نصب‌هایی که ردیفِ `vertical` ندارند (پیش‌فرض: نورومانیتورینگ)
-- دست‌نخورده می‌مانند.
UPDATE "features"
SET "enabled" = true, "min_level" = 2, "updated_at" = now()
WHERE "key" = 'surgeon'
  AND "enabled" = false
  AND EXISTS (SELECT 1 FROM "settings" WHERE "key" = 'vertical' AND "value" = 'clinic');
