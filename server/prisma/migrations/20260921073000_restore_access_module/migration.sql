-- بازگرداندنِ «سطوحِ دسترسی» روی نصب‌هایی که یک‌بار حوزه‌شان عوض شده است.
--
-- ⚠️ همان تلهٔ migrationِ قبلی، از سمتِ دیگرش: `setVertical` هر کلیدی را که در
-- پلانِ حوزه **نیست** خاموش می‌کند، و `access` (ماتریسِ دسترسی) در هیچ‌کدام از
-- سه حوزه نیامده بود. پس اولین تغییرِ حوزه — حتی انتخابِ دوبارهٔ همان حوزه —
-- صفحهٔ «سطوحِ دسترسی» را برای همیشه از دسترس خارج می‌کرد؛ یعنی دقیقاً همان
-- جایی که مدیر باید برود تا دسترسی‌ها را درست کند. `transport` هم همین را
-- خورده بود.
--
-- این‌جا فقط `access` برگردانده می‌شود: زیرساختِ مدیریت است و خاموش‌بودنش
-- هیچ‌وقت تصمیمِ کسی نبوده. `transport` عمداً دست نمی‌خورد — از حالا در پلانِ
-- حوزه‌های شرکتی هست و با سوییچِ بعدی روشن می‌شود، ولی روشن‌کردنِ خودکارش روی
-- نصبِ موجود یعنی ظاهرشدنِ یک پرتالِ پنهان بدونِ اینکه کسی خواسته باشد.
-- (`eligibility()` هرحال فقط به دارندهٔ رکوردِ نیروی حمل نشانش می‌دهد.)
UPDATE "features"
SET "enabled" = true, "updated_at" = now()
WHERE "key" = 'access' AND "enabled" = false;
