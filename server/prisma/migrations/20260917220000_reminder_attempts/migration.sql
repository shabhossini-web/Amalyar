-- W1.9 — شمارندهٔ تلاشِ ارسالِ یادآوری (قراردادِ §۸)
--
-- تا امروز وضعیتِ `uncertain` عملاً **نهایی** بود: `sendReminders` فقط
-- ردیف‌های `pending` را برمی‌دارد، پس پیامی که نتیجه‌اش نامعلوم مانده بود
-- هیچ‌وقت دوباره امتحان نمی‌شد و بی‌سروصدا می‌ماند.
--
-- حالا `uncertain` تا سه بار با مکثِ ۵/۱۵/۴۵ دقیقه برمی‌گردد به صف و بعد
-- `failed` می‌گیرد. برای اینکه بدانیم «چندمین تلاش»، همین ستون لازم است.
--
-- `DEFAULT 0` و `NOT NULL`: ردیف‌های موجود هیچ‌کدام تلاشِ شمرده‌شده ندارند و
-- مقدارِ ساختگی نباید بگیرند؛ صفر همان «هنوز شمرده نشده» است.
ALTER TABLE "reminders" ADD COLUMN "attempts" INTEGER NOT NULL DEFAULT 0;
