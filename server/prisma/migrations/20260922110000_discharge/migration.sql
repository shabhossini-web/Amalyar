-- **ترخیص، مرحلهٔ سومِ چرخه است — نه مترادفِ «پایانِ عمل».**
--
-- بازخوردِ مالک: «توی جراحی یه پایانِ عمل داریم یه ترخیص». تا امروز فقط
-- `op_end_time` بود و همان را «تمام شد» می‌خواندیم؛ ولی بیمار بعد از پایانِ
-- عمل هنوز در ریکاوری است و وضعیتش هنگامِ ترخیص یک سندِ جداست.
--
-- ⚠️ فقط **زمان** ستون می‌شود، نه متنِ وضعیت: متن یک `ClinicalNote` با
-- `kind='discharge'` است — نسخه‌دار، امضادار و از همان تبِ شرح‌های پرونده
-- دیدنی. ستونِ متنی یعنی همان متن یک‌بار دیگر جایی بیرونِ پرونده هم باشد،
-- و دقیقاً همان دو-نسخه‌ای که در `chief_complaint` تازه جمعش کردیم.
ALTER TABLE "visits" ADD COLUMN "discharge_at" TIMESTAMP(3);

-- «چه کسی امروز ترخیص شده» باید با یک WHERE پرسیده شود، نه با اسکنِ کلِ جدول.
CREATE INDEX "visits_discharge_at_idx" ON "visits"("discharge_at");
