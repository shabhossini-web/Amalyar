/** واژگانِ یک حوزه؛ حوزهٔ ناشناخته به پیش‌فرض برمی‌گردد نه به undefined. */
export const termsFor = (vertical) => TERMS[vertical] ?? TERMS[DEFAULT_VERTICAL];

/**
 * سه مفهومی که در رابط مدام یکی گرفته می‌شوند (یافتهٔ U15 سندِ بازبینی).
 *
 * | مفهوم | یعنی | کِی وجود دارد |
 * |---|---|---|
 * | **نوبت** | زمانی که بیمار رزرو کرده | *پیش* از اینکه چیزی رخ دهد؛ ممکن است هرگز نیاید |
 * | **مراجعه** (`termsFor(v).visit`) | خودِ رویداد و پرونده‌اش | وقتی بیمار آمد یا عمل ثبت شد |
 * | **کار** | قلمی در صفِ پیگیری، با مسئول و سررسید | *پس* از مراجعه، یا مستقل از آن |
 *
 * یک نوبت مراجعه **نیست** — تا وقتی «شروعِ مراجعه» زده نشود هیچ پرونده‌ای
 * ساخته نمی‌شود. و یک کار نه نوبت است نه مراجعه؛ ممکن است اصلاً به بیمار
 * وصل نباشد (مثلِ «رویدادِ پردازش‌نشده» در نمای استثنا).
 *
 * ⚠️ چرا `visit` این‌جا نیست: تنها واژهٔ این سه‌تایی است که **با حوزه فرق
 * می‌کند** (مراجعه / عمل / ویزیت)، پس جایش `termsFor(vertical).visit` است.
 * «نوبت» و «کار» در هر سه حوزه یکی‌اند و طبقِ قاعدهٔ همین فایل (فقط چیزی که
 * واقعاً فرق می‌کند در `TERMS` می‌آید) بیرونِ آن نشسته‌اند.
 */
