async function database(control = false) {
  const db = new PGlite(); await db.waitReady;
  const root = new URL(`../../server/prisma/${control ? 'control/' : ''}migrations/`, import.meta.url);
  for (const dir of (await readdir(root)).sort()) if (dir.startsWith('20')) await db.exec(await readFile(new URL(`${dir}/migration.sql`, root), 'utf8'));
  const server = createServer(db, { logLevel: 0 }); await new Promise(r => server.listen(0, '127.0.0.1', r));
  const client = new (control ? ControlClient : PrismaClient)({ datasources: { db: { url: `postgresql://postgres@127.0.0.1:${server.address().port}/postgres?connection_limit=1` } } });
  resources.push({ db, server, client }); return client;
}
