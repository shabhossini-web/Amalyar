/** Real services and disposable database. No production data, messages or stock mutations. */
import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { PGlite } from '@electric-sql/pglite';
import { createServer } from 'pglite-server';
const require = createRequire(import.meta.url);
const { PrismaClient } = require('../../server/node_modules/@prisma/client');
const cls = (f, n) => require(`../../server/dist/${f}.js`)[n];
const db = new PGlite(); await db.waitReady;
const server = createServer(db, { logLevel: 0 });
let prisma, count = 0, vertical = 'ionm';
const pass = name => console.log(`PASS ${++count}: ${name}`);
try {
  const migrations = new URL('../../server/prisma/migrations/', import.meta.url);
  for (const dir of (await readdir(migrations)).sort()) if (dir.startsWith('20')) await db.exec(await readFile(new URL(`${dir}/migration.sql`, migrations), 'utf8'));
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  prisma = new PrismaClient({ datasources: { db: { url: `postgresql://postgres@127.0.0.1:${server.address().port}/postgres?connection_limit=1` } } });
  const config = { vertical: async () => vertical };
  const forms = new (cls('patients/forms.service', 'FormsService'))(prisma, config);
  const audit = new (cls('audit/audit.service', 'AuditService'))(prisma);
  const reminders = { syncNextVisit: async () => {}, syncAppointment: async () => {} };
  const events = new (cls('work/events.service', 'EventsService'))(prisma); // W2.2: outboxِ رویداد — همان سرویسِ واقعی
  const patients = new (cls('patients/patients.service', 'PatientsService'))(prisma, audit, forms, reminders, events);
  const treasury = new (cls('patients/treasury.service', 'TreasuryService'))(prisma, audit);
  const billing = new (cls('patients/billing.service', 'BillingService'))(prisma, audit, {}, treasury);
  const intake = new (cls('patients/intake.service', 'IntakeService'))(prisma, audit, patients, {}, billing, {}, forms, {}, { require: () => ({ hostname: 'fixture.test' }) }, {}, { sendSms: async () => {} }, reminders, {}, events);
  const portal = new (cls('patients/surgeon-portal.service', 'SurgeonPortalService'))(prisma, config, audit);
  const dispatch = new (cls('patients/dispatch.service', 'DispatchService'))(prisma, audit);
  const admin = await prisma.account.create({ data: { passwordHash: 'fixture', level: 6, status: 'active', person: { create: { firstName: 'مدیر', lastName: 'تست' } } } });
  const patient = await prisma.patient.create({ data: { code: 'WF-1', firstName: 'بیمار', lastName: 'تست' } });
  const surgeon = await prisma.surgeon.create({ data: { person: { create: { firstName: 'جراح', lastName: 'اول', phone: '09123456789' } } } });
  const otherSurgeon = await prisma.surgeon.create({ data: { person: { create: { firstName: 'جراح', lastName: 'دوم', phone: '09123456788' } } } });
  const hospital = await prisma.hospital.create({ data: { name: 'مرکز تست' } });
  const item = await prisma.item.create({ data: { name: 'پیچ تست' } });
  const inactive = await prisma.item.create({ data: { name: 'غیرفعال', active: false } });
  const procedure = await prisma.procedureType.create({ data: { name: 'عمل تست', needs: { create: [{ itemId: item.id, quantity: 4 }] } } });
  const dto = { surgeonId: surgeon.id, hospitalId: hospital.id, procedureTypeId: procedure.id, opDate: '2026-09-10', registerPayment: false };
  const submission = (formId, data = {}) => prisma.intakeSubmission.create({ data: { token: `wf-${Math.random()}`, patientId: patient.id, formId, amount: 0, expiresAt: new Date('2027-01-01'), status: 'pending_approval', data } });
  for (const profile of ['ionm', 'implant', 'clinic']) {
    vertical = profile;
    await prisma.formDef.deleteMany(); await prisma.setting.deleteMany({ where: { key: { startsWith: 'registration_' } } });
    const all = await forms.list();
    const reg = all.find(f => f.key === `intake.${profile}`);
    assert.ok(reg); assert.equal(reg.scope, 'intake');
    assert.equal(reg.visitKind, profile === 'clinic' ? 'clinic' : 'surgery');
    assert.equal(all.filter(f => f.scope === 'intake').length, 1);
    assert.equal(reg.fields.some(f => f.key === 'prescription' && f.required), profile === 'implant');
    if (profile === 'clinic') assert.deepEqual((await forms.visitKinds()).map(f => f.kind).sort(), ['clinic', 'surgery']);
    assert.equal((await intake.formsForLinks()).find(f => f.recommended)?.id, reg.id);
    const publicForm = await intake.formView(reg.id);
    assert.equal(publicForm.fields.some(f => f.key === 'prescription'), profile === 'implant');
    assert.equal(publicForm.fields.some(f => f.key === 'chiefComplaint'), profile === 'clinic');
    assert.ok(publicForm.fields.every(f => !['amount', 'techId', 'opReport'].includes(f.key)));
    pass(`${profile}: independent recommended registration and correct visit kinds`);
    // Preserve all administrator definitions, including required amount zero and renamed fields.
    const amount = await prisma.formField.findFirst({ where: { form: { key: `visit.${reg.visitKind}` }, key: 'amount' } });
    if (amount) await prisma.formField.update({ where: { id: amount.id }, data: { required: false } });
    const row = await submission(reg.id, profile === 'clinic' ? { chiefComplaint: 'علت مراجعه آزمایشی' } : {});
    let prescription, foreignDocument;
    if (profile === 'implant') {
      await assert.rejects(() => intake.approve(row.id, { ...dto, requiredItems: [] }, admin), /اقلام/);
      await assert.rejects(() => intake.approve(row.id, { ...dto, requiredItems: [{ itemId: inactive.id, quantity: 2 }] }, admin));
      assert.equal((await prisma.intakeSubmission.findUnique({ where: { id: row.id } })).status, 'pending_approval');
      prescription = await prisma.document.create({ data: { patientId: patient.id, category: 'other', fileName: 'instruction.pdf', mimeType: 'application/pdf', size: 12, sha256: 'prescription' } });
      const foreignPatient = await prisma.patient.create({ data: { code: 'WF-FOREIGN', firstName: 'دیگر', lastName: 'بیمار' } });
      foreignDocument = await prisma.document.create({ data: { patientId: foreignPatient.id, category: 'receipt', fileName: 'private.jpg', mimeType: 'image/jpeg', size: 12, sha256: 'foreign' } });
      await prisma.intakeSubmission.update({ where: { id: row.id }, data: { data: { prescription: { id: prescription.id }, receiptDocumentId: foreignDocument.id } } });
      pass('implant: empty/inactive requirements fail before creating a visit');
    }
    const approved = await intake.approve(row.id, dto, admin);
    const visit = await prisma.visit.findUnique({ where: { id: approved.visitId } });
    assert.equal(visit.kind, reg.visitKind);
    assert.equal(visit.requiredItems?.[0]?.quantity ?? null, profile === 'implant' ? 4 : null);
    assert.equal(await prisma.payment.count({ where: { visitId: visit.id } }), 0);
    assert.equal(await prisma.charge.count({ where: { visitId: visit.id } }), 0);
    if (prescription) {
      assert.equal((await prisma.document.findUnique({ where: { id: prescription.id } })).visitId, visit.id);
      assert.equal((await prisma.document.findUnique({ where: { id: foreignDocument.id } })).visitId, null);
    }
    pass(`${profile}: approval respects kind; requirements do not charge or pay`);
    await prisma.formField.update({ where: { id: reg.fields[0].id }, data: { label: 'نام سفارشی', required: false } });
    await forms.list(); assert.equal((await forms.byKey(reg.key)).fields[0].label, 'نام سفارشی');
    await prisma.formDef.delete({ where: { id: reg.id } });
    assert.equal((await forms.list()).some(f => f.key === reg.key), false);
    pass(`${profile}: custom definitions preserved and deliberate deletion is not reseeded`);
  }
  vertical = 'implant';
  const grant = await portal.grantAccount(surgeon.id, admin);
  const doctor = await prisma.account.findUnique({ where: { id: grant.id } });
  assert.equal(doctor.passwordHash, ''); assert.equal(doctor.level, 2); assert.equal(doctor.personId, surgeon.personId); assert.equal(doctor.jobRole, 'doctor');
  assert.equal((await portal.grantAccount(surgeon.id, admin)).existing, true);
  await assert.rejects(() => portal.grantAccount(otherSurgeon.id, doctor), /مدیر/);
  pass('surgeon account uses existing identity, OTP claim and limited level; grant is admin only');
  const ai = new (cls('ai/ai.service', 'AiService'))(prisma, { ai: async () => ({ enabled: false, models: {} }) }, {});
  assert.equal((await ai.status(doctor)).enabled, false);
  await prisma.feature.upsert({ where: { key: 'surgeon' }, create: { key: 'surgeon', enabled: false, minLevel: 2 }, update: { enabled: false } });
  await assert.rejects(() => ai.status(doctor));
  await prisma.feature.update({ where: { key: 'surgeon' }, data: { enabled: true } });
  await assert.rejects(() => ai.status({ id: -1, level: 2 }));
  pass('limited surgeon can use text assistance only while dynamic portal access is enabled');
  const other = await prisma.visit.create({ data: { patientId: patient.id, seq: 20, surgeonId: otherSurgeon.id } });
  const own = await prisma.visit.create({ data: { patientId: patient.id, seq: 21, surgeonId: surgeon.id, opDate: new Date('2026-09-10'), procedureTypeId: procedure.id } });
  const doc = await prisma.document.create({ data: { patientId: patient.id, visitId: own.id, category: 'other', fileName: 'order.pdf', mimeType: 'application/pdf', size: 100, sha256: 'fixture' } });
  const receipt = await prisma.document.create({ data: { patientId: patient.id, visitId: own.id, category: 'receipt', fileName: 'receipt.jpg', mimeType: 'image/jpeg', size: 100, sha256: 'fixture2' } });
  const listed = await portal.list(doctor, '', Infinity);
  assert.equal(listed.page, 1); assert.ok(listed.rows.some(v => v.id === own.id)); assert.ok(!listed.rows.some(v => v.id === other.id));
  assert.equal(listed.rows.find(v => v.id === own.id).requiredItems[0].quantity, 4);
  await portal.saveInstructions(own.id, { instructions: 'فقط متن' }, doctor);
  assert.equal((await prisma.visit.findUnique({ where: { id: own.id } })).requiredItems, null);
  assert.ok(!JSON.stringify(listed).includes('receipt.jpg')); assert.ok(listed.rows.every(v => !('paid' in v) && !('bankAccount' in v)));
  assert.equal((await portal.document(own.id, doc.id, doctor)).id, doc.id);
  await assert.rejects(() => portal.document(own.id, receipt.id, doctor));
  await assert.rejects(() => portal.document(other.id, doc.id, doctor));
  await assert.rejects(() => portal.saveInstructions(other.id, { instructions: 'غیرمجاز' }, doctor));
  pass('surgeon reads/writes own assignments only; receipts and financial data excluded');
  await portal.saveInstructions(own.id, { instructions: ' دستور تست ', requiredItems: [{ itemId: item.id, quantity: 7, notes: 'اندازه انتخابی' }] }, doctor);
  const saved = await prisma.visit.findUnique({ where: { id: own.id } });
  assert.equal(saved.surgeonInstructions, 'دستور تست'); assert.equal(saved.requiredItems[0].quantity, 7);
  assert.equal(await prisma.auditEvent.count({ where: { action: 'surgeon.instructions' } }), 2);
  assert.equal(await prisma.charge.count({ where: { visitId: own.id } }), 0);
  const shape = dispatch.shape({ ...saved, patient, stockTransfers: [{ code: 'T1', toLocation: 'hospital', movements: [{ location: 'hospital', quantity: 3, lot: { itemId: item.id, item } }, { location: 'stock', quantity: 3, lot: { itemId: item.id, item } }] }], procedureType: { name: 'عمل', needs: [{ itemId: item.id, quantity: 4, item }] }, settlements: [] });
  assert.equal(shape.missingNeeds[0].quantity, 4); assert.equal(shape.requiredItems[0].quantity, 7); assert.equal(shape.surgeonInstructions, 'دستور تست');
  pass('case requirements override procedure defaults; dispatch counts destination quantity and exposes instructions');
  await prisma.document.update({ where: { id: doc.id }, data: { deletedAt: new Date() } });
  await assert.rejects(() => portal.document(own.id, doc.id, doctor));
  await prisma.surgeon.update({ where: { id: surgeon.id }, data: { active: false } });
  await assert.rejects(() => portal.list(doctor));
  pass('deleted document and inactive surgeon lose access');
  vertical = 'clinic'; await assert.rejects(() => portal.list(admin), /مطب/);
  assert.equal((await prisma.account.findUnique({ where: { id: doctor.id } })).level, 2);
  pass('clinic uses dashboard; switching profile never promotes doctors to owner');
  console.log(`${count} profile workflow scenarios passed`);
} finally { if (prisma) await prisma.$disconnect(); server.close(); await db.close(); }
