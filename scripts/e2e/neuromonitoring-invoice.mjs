/** Disposable real database: issuance, tariff priority, retained payments and versions. */
import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { PGlite } from '@electric-sql/pglite';
import { createServer } from 'pglite-server';
const require = createRequire(import.meta.url);
const { PrismaClient } = require('../../server/node_modules/@prisma/client');
const cls = (f, n) => require(`../../server/dist/${f}.js`)[n];
const db = new PGlite(); await db.waitReady;
const server = createServer(db, { logLevel: 0 });
let prisma, count = 0;
const pass = name => console.log(`PASS ${++count}: ${name}`);
try {
  const migrations = new URL('../../server/prisma/migrations/', import.meta.url);
  for (const dir of (await readdir(migrations)).sort()) if (dir.startsWith('20')) await db.exec(await readFile(new URL(`${dir}/migration.sql`, migrations), 'utf8'));
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  prisma = new PrismaClient({ datasources: { db: { url: `postgresql://postgres@127.0.0.1:${server.address().port}/postgres?connection_limit=1` } } });
  pass('all migrations apply without an existing database');
  const audit = new (cls('audit/audit.service', 'AuditService'))(prisma);
  const billing = new (cls('patients/billing.service', 'BillingService'))(prisma, audit, { returnToStock: () => { throw Error('Unexpected inventory mutation'); } }, {});
  const control = { centralTariff: { findMany: async () => [{ year: '1405', sector: 'public', professional: 900, technical: 800, anesthesia: 0, active: true }] } };
  const settings = new (cls('config/settings.service', 'SettingsService'))(prisma, audit, { require: () => ({ tenantId: 'fixture-company' }) }, control);
  const codes = new (cls('patients/service-codes.service', 'ServiceCodesService'))(prisma, control);
  const invoices = new (cls('patients/invoices.service', 'InvoicesService'))(prisma, billing, codes, settings);
  const user = await prisma.account.create({ data: { username: 'invoice-fixture', passwordHash: 'not-a-login', level: 6, person: { create: { firstName: 'مدیر', lastName: 'آزمایشی' } } } });
  const patient = await prisma.patient.create({ data: { code: 'AM-LOCAL', firstName: 'بیمار', lastName: 'آزمایشی' } });
  const hospital = await prisma.hospital.create({ data: { name: 'مرکز دولتی', sector: 'public' } });
  const bank = await prisma.bankAccount.create({ data: { ownerName: 'شرکت تست', classification: 'formal' } });
  const v = await prisma.visit.create({ data: { patientId: patient.id, hospitalId: hospital.id, opDate: new Date('2026-09-08'), opStartTime: '23:30', opEndTime: '02:00', invoiceType: 'formal', invoiceBankAccountId: bank.id } });
  await settings.update({ company_legal_name: 'شرکت نورومانیتورینگ تست', invoice_prefix: 'NM-', invoice_notes: 'یادداشت ثابت', invoice_formal_name: 'صادرکننده رسمی', invoice_informal_name: 'صادرکننده غیررسمی' }, user);
  await prisma.serviceCode.create({ data: { code: '901300', title: 'مانیتورینگ', version: 'fixture', rvuProfessional: 15000, rvuTechnical: 7300 } });
  const local = await prisma.tariff.create({ data: { year: '1405', sector: 'public', professional: 101, technical: 203, anesthesia: 0 } });
  const dto = { code: '901300', year: '1405', hours: 3, deviceOwner: 'hospital' };
  const defaults = await invoices.list(v.id, user);
  assert.equal(defaults.hours, 3); assert.equal(defaults.year, '1405'); assert.equal(defaults.sector, 'public');
  pass('overnight duration and half-hour rounding; year and hospital sector from visit');
  const preview = await invoices.price(v.id, dto, user);
  assert.equal(preview.professional, 4545); assert.equal(preview.technical, 4446); assert.equal(preview.total, 8991);
  assert.equal(preview.coefficients.technical, 7.3); assert.equal(preview.factors.professional, 101);
  pass('local tariff beats central; professional and technical separately rounded in TOMAN');
  await assert.rejects(() => invoices.price(v.id, { ...dto, year: '1404' }, user), /تعرفه/);
  await assert.rejects(() => invoices.price(v.id, { ...dto, hours: 0 }, user));
  await assert.rejects(() => invoices.price(v.id, { ...dto, hours: 1.5 }, user));
  pass('missing year/sector tariff and invalid hours rejected');
  await prisma.tariff.update({ where: { id: local.id }, data: { active: false } });
  assert.equal((await invoices.price(v.id, dto, user)).factors.professional, 900);
  await prisma.tariff.update({ where: { id: local.id }, data: { active: true } });
  pass('central tariff used only when no active local tariff exists');
  const row = await invoices.addService(v.id, { ...dto, total: 1, professional: 1 }, user);
  assert.equal(row.amount, 8991); assert.equal(row.neuroDetail.total, 8991);
  const payment = await prisma.payment.create({ data: { visitId: v.id, amount: 8991, paidAt: new Date('2026-09-08'), method: 'transfer', bankAccountId: bank.id } });
  pass('amounts recalculated on save, browser-supplied totals ignored');
  const first = await invoices.issue(v.id, 'formal', user);
  assert.match(first.number, /^NM-F-\d{6}$/); assert.equal(first.snapshot.billing.due, 0);
  assert.equal(first.snapshot.template.brand.legalName, 'صادرکننده رسمی');
  assert.deepEqual(Object.keys(first.snapshot.billing.invoiceBankAccount).sort(), ['accountNumber', 'bankName', 'iban', 'id', 'ownerName']);
  assert.equal((await invoices.issue(v.id, 'formal', user)).id, first.id);
  assert.equal(await prisma.invoiceDocument.count(), 1);
  pass('settled invoice issued and repeat click returns the same serial');
  const concurrent = await Promise.all([invoices.issue(v.id, 'formal', user), invoices.issue(v.id, 'formal', user)]);
  assert.equal(concurrent[0].id, concurrent[1].id);
  pass('concurrent issuance is idempotent');
  const extra = await billing.addCharge(v.id, { title: 'قلم اضافه', unitPrice: 1000 }, user);
  const second = await invoices.issue(v.id, 'formal', user);
  assert.notEqual(second.id, first.id); assert.equal(second.snapshot.billing.due, 1000);
  assert.ok((await invoices.document(v.id, first.id, user)).supersededAt);
  assert.deepEqual((await invoices.document(v.id, first.id, user)).snapshot, first.snapshot);
  pass('new issue supersedes while retaining immutable old financial snapshot');
  await billing.removeCharge(extra.id, user);
  assert.deepEqual(await prisma.payment.findUnique({ where: { id: payment.id } }), payment);
  assert.equal((await billing.get(v.id, user)).due, 0);
  await billing.removeCharge(row.id, user);
  assert.equal((await billing.get(v.id, user)).due, -8991);
  assert.equal((await invoices.document(v.id, first.id, user)).snapshot.billing.total, 8991);
  await assert.rejects(() => invoices.issue(v.id, 'formal', user), /اقلام/);
  pass('charge deletion preserves payment and old invoice; overpayment becomes credit');
  await invoices.addService(v.id, dto, user);
  await billing.setPricing(v.id, { pricingModel: 'global', globalAmount: 30000000 }, user);
  const global = await invoices.issue(v.id, 'formal', user);
  assert.equal(global.snapshot.billing.total, 30000000); assert.equal(global.snapshot.billing.itemsTotal, 8991); assert.equal(global.snapshot.billing.due, 29991009);
  pass('global amount remains canonical when itemized neuro services differ');
  await settings.update({ invoice_notes: 'قالب جدید', invoice_formal_name: 'نام جدید شرکت' }, user);
  const updated = await invoices.issue(v.id, 'formal', user);
  assert.equal(updated.snapshot.template.notes, 'قالب جدید'); assert.equal((await invoices.document(v.id, first.id, user)).snapshot.template.notes, 'یادداشت ثابت');
  pass('company template changes apply only to new issued versions');
  await assert.rejects(() => invoices.issue(v.id, 'informal', user), /حساب/);
  await prisma.bankAccount.update({ where: { id: bank.id }, data: { active: false } });
  await assert.rejects(() => invoices.issue(v.id, 'formal', user), /حساب/);
  await prisma.bankAccount.update({ where: { id: bank.id }, data: { active: true } });
  pass('invoice variant and active matching bank enforced at issuance');
  const cash = await prisma.payment.create({ data: { visitId: v.id, amount: 100, paidAt: new Date('2026-09-08'), method: 'cash' } });
  assert.equal((await invoices.issue(v.id, 'formal', user)).snapshot.billing.paid, 9091);
  const wrongBank = await prisma.bankAccount.create({ data: { ownerName: 'حساب دیگر', classification: 'formal' } });
  await prisma.payment.update({ where: { id: cash.id }, data: { bankAccountId: wrongBank.id } });
  await assert.rejects(() => invoices.issue(v.id, 'formal', user), /حساب پرداخت/);
  pass('unassigned cash is valid; an explicitly different receiving bank is rejected');
  const outsider = { id: user.id + 1000, level: 2 };
  await assert.rejects(() => invoices.list(v.id, outsider), /مراجعه/);
  await assert.rejects(() => invoices.price(v.id, dto, outsider), /مراجعه/);
  await assert.rejects(() => invoices.issue(v.id, 'formal', outsider), /مراجعه/);
  await assert.rejects(() => invoices.document(v.id, first.id, outsider), /مراجعه/);
  const other = await prisma.visit.create({ data: { patientId: patient.id, seq: 2 } });
  await assert.rejects(() => invoices.document(other.id, first.id, user), /فاکتور/);
  pass('object scope enforced for prices, history, issue and individual document');
  assert.equal(await prisma.auditEvent.count({ where: { action: 'invoice.issue' } }), await prisma.invoiceDocument.count());
  await assert.rejects(() => db.exec(`DELETE FROM visits WHERE id = ${v.id}`), /foreign key/i);
  pass('issued invoices survive deletion attempts and every issue has an audit record');
  console.log(`${count} invoice integration scenarios passed`);
} finally { if (prisma) await prisma.$disconnect(); server.close(); await db.close(); }
