/** Real Prisma/services against disposable PostgreSQL WASM; no production services or SMS. */
import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { PGlite } from '@electric-sql/pglite';
import { createServer } from 'pglite-server';
const require = createRequire(import.meta.url);
const { PrismaClient } = require('../../server/node_modules/@prisma/client');
const cls = (file, name) => require(`../../server/dist/${file}.js`)[name];
const db = new PGlite(); await db.waitReady;
const server = createServer(db, { logLevel: 0 });
let prisma, passed = 0;
const ok = (name) => console.log(`PASS ${++passed}: ${name}`);
try {
  const migrations = new URL('../../server/prisma/migrations/', import.meta.url);
  for (const dir of (await readdir(migrations)).sort()) {
    if (dir.startsWith('20')) await db.exec(await readFile(new URL(`${dir}/migration.sql`, migrations), 'utf8'));
  }
  ok('all tenant migrations apply to an empty PostgreSQL database');
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  prisma = new PrismaClient({ datasources: { db: { url: `postgresql://postgres@127.0.0.1:${server.address().port}/postgres?connection_limit=1` } } });
  const audit = new (cls('audit/audit.service', 'AuditService'))(prisma);
  const forms = new (cls('patients/forms.service', 'FormsService'))(prisma, { vertical: async () => 'clinic' });
  const reminders = { syncNextVisit: async () => {}, syncAppointment: async () => {} };
  const events = new (cls('work/events.service', 'EventsService'))(prisma); // W2.2: outboxِ رویداد — همان سرویسِ واقعی
  const patients = new (cls('patients/patients.service', 'PatientsService'))(prisma, audit, forms, reminders, events);
  const treasury = new (cls('patients/treasury.service', 'TreasuryService'))(prisma, audit);
  const billing = new (cls('patients/billing.service', 'BillingService'))(prisma, audit, {}, treasury);
  const ledger = new (cls('patients/ledger.service', 'LedgerService'))(prisma, audit, treasury);
  const defs = new (cls('patients/definitions.service', 'DefinitionsService'))(prisma);
  const tenant = { require: () => ({ hostname: 'clinic.example.test' }) };
  const intake = new (cls('patients/intake.service', 'IntakeService'))(prisma, audit, patients, {}, billing, {}, forms, {}, tenant, {}, { sendSms: async () => {} }, reminders, {}, events);
  const user = await prisma.account.create({ data: { username: 'fixture-admin', passwordHash: 'not-a-login', level: 6, status: 'active', person: { create: { firstName: 'تست', lastName: 'محلی' } } } });
  const patient = await prisma.patient.create({ data: { code: 'AM-TEST', firstName: 'بیمار', lastName: 'آزمایشی' } });
  // A real required amount field reproduces the reported approval validation.
  const form = await prisma.formDef.create({ data: { key: 'visit.surgery', title: 'عمل', scope: 'visit', visitKind: 'surgery', fields: { create: [
    { key: 'amount', label: 'مبلغ (تومان)', type: 'money', required: true, builtin: true },
    { key: 'sharedNote', label: 'شرح مشترک', type: 'textarea', role: 'doctor', roles: ['doctor', 'technician'] },
  ] } } });
  const bank = await ledger.addAccount({ ownerName: 'شرکت تست', classification: 'formal' }, user);
  const informal = await ledger.addAccount({ ownerName: 'شرکت غیررسمی', classification: 'informal' }, user);
  const legacy = await ledger.addAccount({ ownerName: 'قدیمی' }, user);
  assert.equal(legacy.classification, 'unclassified'); ok('old bank accounts are not silently classified');
  const hospital = await defs.createHospital({ name: 'مرکز دولتی تست', sector: 'public' });
  assert.equal((await defs.listHospitals()).find((r) => r.id === hospital.id).sector, 'public'); ok('hospital sector round-trips through definitions');
  const submission = (discountAmount = 0) => prisma.intakeSubmission.create({ data: { token: `fixture-${Math.random()}`, patientId: patient.id, formId: form.id, amount: 30000000, discountAmount, expiresAt: new Date('2027-01-01'), status: 'pending_approval', data: {} } });
  const first = await submission();
  const approved = await intake.approve(first.id, { registerPayment: true, bankAccountId: bank.id, hospitalId: hospital.id }, user);
  const bill = await billing.get(approved.visitId, user);
  assert.equal(bill.charges.length, 1); assert.equal(bill.charges[0].amount, 30000000);
  assert.equal(bill.payments.length, 1); assert.equal(bill.payments[0].amount, 30000000); assert.equal(bill.due, 0);
  assert.equal(bill.tariffSector, 'public'); ok('30M paid approval succeeds, charges once, records payment, hospital supplies tariff sector');
  await assert.rejects(() => intake.approve(first.id, {}, user));
  assert.equal(await prisma.charge.count({ where: { visitId: approved.visitId } }), 1); ok('repeat approval cannot duplicate amounts');
  const unpaid = await submission();
  const unpaidVisit = await intake.approve(unpaid.id, { registerPayment: false }, user);
  const unpaidBill = await billing.get(unpaidVisit.visitId, user);
  assert.equal(unpaidBill.due, 30000000); assert.equal(unpaidBill.payments.length, 0); ok('unchecked payment records service and preserves debt');
  const discounted = await submission(5000000);
  const discountedVisit = await intake.approve(discounted.id, { bankAccountId: informal.id, paidAmount: 10000000 }, user);
  const discountedBill = await billing.get(discountedVisit.visitId, user);
  assert.equal(discountedBill.charges.length, 2); assert.equal(discountedBill.due, 15000000); ok('discount and partial receipt are independent, without double charging');
  const originalValidate = forms.validateFields.bind(forms);
  let validatedAmount;
  forms.validateFields = (fields, values) => { validatedAmount = values.amount; return originalValidate(fields, values); };
  for (const target of [approved.visitId, unpaidVisit.visitId, discountedVisit.visitId]) {
    const beforeBill = await billing.get(target, user);
    const beforeLedger = await prisma.partnerLedger.count();
    const updated = await patients.updateVisit(target, { opDate: '2026-09-11', notes: 'تغییر تاریخ', extra: { amount: 1 } }, user);
    assert.equal(validatedAmount, beforeBill.total);
    assert.equal(updated.total, beforeBill.total);
    assert.equal(updated.opDate.toISOString().slice(0, 10), '2026-09-11');
    const afterBill = await billing.get(target, user);
    assert.deepEqual(afterBill.charges, beforeBill.charges);
    assert.deepEqual(afterBill.payments, beforeBill.payments);
    assert.equal(afterBill.due, beforeBill.due);
    assert.equal(await prisma.partnerLedger.count(), beforeLedger);
  }
  ok('changing dates validates stored invoice total and preserves charges, payments, debt and ledger for paid/unpaid/discounted visits');
  await prisma.visit.update({ where: { id: unpaidVisit.visitId }, data: { pricingModel: 'global', globalAmount: 42000000 } });
  const globalVisit = await patients.updateVisit(unpaidVisit.visitId, { opDate: '2026-09-12' }, user);
  assert.equal(validatedAmount, 42000000); assert.equal(globalVisit.total, 42000000);
  assert.equal((await billing.get(unpaidVisit.visitId, user)).total, globalVisit.total);
  await prisma.visit.update({ where: { id: unpaidVisit.visitId }, data: { pricingModel: 'coded', globalAmount: null } });
  const free = await patients.createVisit({ patientId: patient.id, kind: 'surgery', amount: 0 }, user);
  await patients.updateVisit(free.id, { opDate: '2026-09-11' }, user);
  assert.equal(validatedAmount, 0);
  assert.equal((await billing.get(free.id, user)).total, 0);
  ok('global and zero-total visits use the same billing calculation during validation');
  const notesField = await prisma.formField.findFirst({ where: { formId: form.id, key: 'notes' } });
  await prisma.formField.update({ where: { id: notesField.id }, data: { active: true, required: true } });
  await assert.rejects(() => patients.updateVisit(approved.visitId, { notes: '' }, user), /را کامل کنید/);
  await patients.updateVisit(approved.visitId, { opDate: '2026-09-13' }, user);
  assert.equal((await patients.getVisit(approved.visitId, user)).notes, 'تغییر تاریخ');
  await prisma.formField.update({ where: { id: notesField.id }, data: { required: false } });
  forms.validateFields = originalValidate;
  ok('PATCH preserves omitted fields and rejects clearing a supplied required field');
  const bad = await submission(); const visitsBefore = await prisma.visit.count();
  await assert.rejects(() => intake.approve(bad.id, { bankAccountId: 999999 }, user));
  assert.equal(await prisma.visit.count(), visitsBefore); assert.equal((await prisma.intakeSubmission.findUnique({ where: { id: bad.id } })).status, 'pending_approval'); ok('invalid bank fails before approval mutates visit or status');
  await billing.setInvoiceAccount(approved.visitId, { invoiceType: 'formal', bankAccountId: bank.id }, user);
  await assert.rejects(() => billing.setInvoiceAccount(approved.visitId, { invoiceType: 'formal', bankAccountId: informal.id }, user));
  await assert.rejects(() => billing.addPayment(approved.visitId, { amount: 1000, bankAccountId: informal.id }, user));
  await assert.rejects(() => ledger.patchAccount(bank.id, { classification: 'informal' }, user));
  ok('invoice/account matching enforced on server and linked account type protected');
  // پولِ نقدی حسابِ بانکی ندارد؛ قیدِ «همان حسابِ فاکتور» فقط برای مسیرِ بانکی است.
  const cashPay = await billing.addPayment(approved.visitId, { amount: 1000, method: 'cash' }, user);
  assert.equal(cashPay.bankAccountId, null);
  await assert.rejects(() => billing.addPayment(approved.visitId, { amount: 1000, method: 'transfer' }, user), /کارتی|حساب/);
  await assert.rejects(() => billing.addPayment(approved.visitId, { amount: 1000, method: 'card', bankAccountId: informal.id }, user));
  await assert.rejects(() => billing.addPayment(approved.visitId, { amount: 1000, method: 'cash', bankAccountId: informal.id }, user));
  assert.equal((await billing.addPayment(approved.visitId, { amount: 500, method: 'card', bankAccountId: bank.id }, user)).bankAccountId, bank.id);
  ok('cash on an invoice-linked visit needs no bank account; card/transfer/cheque must use the linked account; a mismatched account is refused for every method');
  const field = await prisma.formField.findFirst({ where: { formId: form.id, key: 'sharedNote' } });
  await forms.patchField(field.id, { roles: ['secretary', 'technician'] });
  const def = await forms.byKey('visit.surgery');
  assert.deepEqual(def.fields.find((f) => f.key === 'sharedNote').roles, ['secretary', 'technician']);
  await patients.assertRoleOwnership('surgery', { extra: { sharedNote: 'متن' } }, { level: 5, jobRole: 'technician' });
  await patients.assertRoleOwnership('surgery', { extra: { sharedNote: 'متن' } }, { level: 5, jobRole: 'secretary' });
  await assert.rejects(() => patients.assertRoleOwnership('surgery', { extra: { sharedNote: 'متن' } }, { level: 5, jobRole: 'doctor' }));
  await assert.rejects(() => forms.patchField(field.id, { roles: ['unknown'] }));
  await forms.patchField(field.id, { role: 'doctor' });
  assert.deepEqual((await forms.byKey('visit.surgery')).fields.find((f) => f.id === field.id).roles, ['doctor']);
  ok('multi-role grants both roles, denies outsiders, validates keys, supports legacy clients');
  const follow = await forms.installFollowUp();
  assert.equal(follow.active, false); assert.equal(follow.followUp, 'general');
  await forms.patchField(follow.fields[0].id, { label: 'متن اختصاصی مرکز' });
  assert.equal((await forms.installFollowUp()).fields[0].label, 'متن اختصاصی مرکز'); ok('follow-up preset installs for review and never overwrites clinic definitions');
  await prisma.formDef.update({ where: { id: follow.id }, data: { active: true } });
  const realReminders = new (cls('patients/reminders.service', 'RemindersService'))(prisma, {}, {}, tenant);
  const v = { id: approved.visitId, patientId: patient.id, patient, opDate: new Date('2026-09-07'), procedureTypeId: null, diagnosisId: null };
  const day0 = await realReminders.followUpUrl(v, [0]); const day7 = await realReminders.followUpUrl(v, [7]);
  assert.notEqual(day0, day7);
  await prisma.intakeSubmission.update({ where: { token: day0.split('/').at(-1) }, data: { status: 'approved' } });
  assert.equal(await realReminders.followUpUrl(v, [0]), day0);
  assert.notEqual(await realReminders.followUpUrl({ ...v, id: unpaidVisit.visitId }, [7]), day7);
  ok('follow-up links distinct per visit/day and stable after completion');
  const accounts = new (cls('accounts/accounts.service', 'AccountsService'))(prisma, { publicUser: (a) => ({ id: a.id, level: a.level, jobRole: a.jobRole }) });
  const tech = await accounts.createTechnician({ firstName: 'کارشناس', lastName: 'آزمایشی', phone: '09123456789' }, user.id);
  assert.equal(tech.level, 2); assert.equal(tech.jobRole, 'technician');
  await assert.rejects(() => accounts.createTechnician({ firstName: 'کارشناس', lastName: 'آزمایشی', phone: '09123456789' }, user.id));
  assert.ok((await defs.listTechs()).some((t) => t.id === tech.id)); ok('quick technician creation yields selectable account and rejects duplicate person');
  console.log(`${passed} integration scenarios passed`);
} finally { if (prisma) await prisma.$disconnect(); server.close(); await db.close(); }
